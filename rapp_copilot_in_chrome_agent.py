"""
rapp_copilot_in_chrome_agent.py -- install, verify, and diagnose the Chrome
browser-automation bridge that lets GitHub Copilot CLI drive real Chrome.

Stdlib only, Python 3.9+. No framework, no install step.

    python3 rapp_copilot_in_chrome_agent.py '{"action": "doctor"}'
    echo '{"action": "install"}' | python3 rapp_copilot_in_chrome_agent.py
    python3 rapp_copilot_in_chrome_agent.py --tool

Companion to SKILL.md, which carries the browser-usage guide. See
https://github.com/kody-w/rapp-copilot-in-chrome
"""

