    _args = sys.argv[1:]
    if _args and _args[0] == "--tool":
        print(json.dumps(RappCopilotInChromeAgent().to_tool(), indent=2))
    else:
        _raw = _args[0] if _args else (sys.stdin.read().strip() or "{}")
        print(RappCopilotInChromeAgent().perform(**json.loads(_raw)))
